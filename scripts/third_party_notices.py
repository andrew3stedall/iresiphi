#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md from the locked Cargo dependency graph.

Usage: python scripts/third_party_notices.py [--output THIRD_PARTY_NOTICES.md]

Runs `cargo metadata --locked` for the Linux x86_64 and aarch64 targets, once for
the Rust crate (default features) and once for the Python wheel (`python`
feature), walks the resolved graph from `iresiphi` through normal and build
dependencies (never dev-dependencies), and records each crate's declared SPDX
license expression. NOTICE files shipped in a crate's source are copied in full,
because Apache-2.0 section 4(d) requires redistributing them.

The license fields come from each crate's own Cargo.toml. This inventory is an
input to review, not a legal determination.
"""
import argparse
import json
import subprocess
from pathlib import Path

TARGETS = ["x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu"]
VARIANTS = {"rust crate (default features)": [], "python wheel (feature python)": ["--features", "python"]}


def metadata(extra, target):
    command = ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", target, *extra]
    return json.loads(subprocess.run(command, check=True, capture_output=True, text=True).stdout)


def proc_macro(package):
    return any("proc-macro" in target["kind"] for target in package["targets"])


def walk(meta):
    """Package ids reachable from the root, with how each is needed."""
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {node["id"]: node for node in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    kinds = {}
    stack = [(root, "normal")]
    while stack:
        package, kind = stack.pop()
        previous = kinds.get(package)
        if previous == "normal" or previous == kind:
            continue
        kinds[package] = "normal" if "normal" in (previous, kind) else kind
        for dep in nodes[package]["deps"]:
            dep_kinds = {k["kind"] or "normal" for k in dep["dep_kinds"]}
            dep_kinds.discard("dev")
            for dep_kind in dep_kinds:
                # Anything only a build script or proc macro needs is build-time.
                compile_time = "build" in (dep_kind, kinds[package]) or proc_macro(by_id[dep["pkg"]])
                stack.append((dep["pkg"], "build" if compile_time else "normal"))
    kinds.pop(root)
    return kinds


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("THIRD_PARTY_NOTICES.md"))
    args = parser.parse_args()
    packages, usage = {}, {}
    for variant, extra in VARIANTS.items():
        for target in TARGETS:
            meta = metadata(extra, target)
            by_id = {p["id"]: p for p in meta["packages"]}
            for package_id, kind in walk(meta).items():
                package = by_id[package_id]
                key = (package["name"], package["version"])
                packages[key] = package
                entry = usage.setdefault(key, {"variants": set(), "kinds": set()})
                entry["variants"].add(variant)
                entry["kinds"].add(kind)
    licenses = {}
    for key, package in packages.items():
        licenses.setdefault(package.get("license") or f"license-file: {package.get('license_file')}", []).append(key)
    lines = [
        "# Third-party notices",
        "",
        "Generated by `scripts/third_party_notices.py` from `Cargo.lock` with `cargo metadata --locked` for "
        + " and ".join(f"`{t}`" for t in TARGETS) + ". Do not edit by hand; rerun the script after a dependency change.",
        "",
        "Iresiphi itself is licensed under Apache-2.0 (see `LICENSE`). The crates below are compiled into the "
        "Rust library and the Python extension module. Each keeps its own license, and the license expression is the one "
        "the crate declares in its `Cargo.toml`; where an expression offers a choice (`A OR B`), Iresiphi's distributions "
        "use the crate under either option. This inventory supports review; it is not legal advice.",
        "",
        "`normal` crates are linked into the built library. `build` crates run only at compile time (build scripts and "
        "procedural macros) and are not shipped in a wheel, though an sdist build downloads and runs them.",
        "",
        f"{len(packages)} crates in total.",
        "",
        "## License expressions",
        "",
        "| License expression | Crates |",
        "| --- | ---: |",
    ]
    for expression, keys in sorted(licenses.items(), key=lambda item: (-len(item[1]), item[0])):
        lines.append(f"| `{expression}` | {len(keys)} |")
    lines += ["", "## Crates", "", "| Crate | Version | License | Needed as | In | Source |", "| --- | --- | --- | --- | --- | --- |"]
    for key in sorted(packages):
        package = packages[key]
        entry = usage[key]
        needed = "normal" if "normal" in entry["kinds"] else "build"
        variants = "both" if len(entry["variants"]) == len(VARIANTS) else "wheel only" if "python" in next(iter(entry["variants"])) else "crate only"
        source = package.get("repository") or "crates.io"
        lines.append(f"| {key[0]} | {key[1]} | `{package.get('license')}` | {needed} | {variants} | {source} |")
    notices = []
    for key in sorted(packages):
        root = Path(packages[key]["manifest_path"]).parent
        for candidate in sorted(root.iterdir()):
            if candidate.is_file() and candidate.name.upper().startswith("NOTICE"):
                notices.append((key, candidate))
    lines += ["", "## NOTICE files", ""]
    if not notices:
        lines.append("No crate in the graph ships a NOTICE file.")
    grouped = {}
    for (name, version), path in notices:
        text = path.read_text(encoding="utf-8", errors="replace").rstrip()
        grouped.setdefault(text, []).append(f"{name} {version} ({path.name})")
    for text, owners in grouped.items():
        lines += [f"### {owners[0]}" + (f" and {len(owners) - 1} more" if len(owners) > 1 else ""), ""]
        if len(owners) > 1:
            lines += ["Identical text ships in: " + ", ".join(owners) + ".", ""]
        lines += ["```text", text, "```", ""]
    args.output.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"{args.output}: {len(packages)} crates, {len(licenses)} license expressions, {len(notices)} NOTICE files, {len(grouped)} distinct")


if __name__ == "__main__":
    main()
